"""
renloc_core/synthesizer/package_synthesizer.py
Ren'Py Localization Package Exporter for `game/tl/vietnamese/`.
Strict Rules:
  - Exactly 4 spaces indentation, 0 tab characters (strictly prevents indentation syntax errors).
  - Emits `translate vietnamese <id>:` blocks for dialogue with source comment `# who "what"`.
  - Emits `translate vietnamese strings:` blocks with `old "..."` and `new "..."`.
  - Injects FontGroup fallback declarations for 134 Vietnamese NFC glyphs.
"""
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, Dict, List, Optional, Set, Tuple

from renloc_core.ast_reader.code_generator import encode_say_string, get_say_code
from renloc_core.static_graph.dialogue_normalizer import DialogueEntity
from renloc_core.static_graph.screen_extractor import ExtractedUIString


@dataclass
class TranslationItem:
    translation_id: str
    original_statement_code: str
    translated_text: str
    who: Optional[str] = None
    attributes: Tuple[str, ...] = ()
    temporary_attributes: Tuple[str, ...] = ()
    with_: Optional[str] = None
    interact: bool = True
    filename: str = "script.rpy"
    linenumber: int = 1


@dataclass
class UIStringTranslationItem:
    original_text: str
    translated_text: str
    filename: str = "screens.rpy"
    linenumber: int = 1


class PackageSynthesizer:
    """
    Exports full `game/tl/vietnamese/` directory structure matching Ren'Py SDK standards.
    """

    INDENT = "    " # Strictly 4 spaces

    def __init__(self, language: str = "vietnamese"):
        self.language = language

    def format_dialogue_block(self, item: TranslationItem) -> str:
        """
        Formats a single translate block:
          # game/script.rpy:36
          translate vietnamese start_d9ca682b:

              # s "Welcome to the old world!"
              s "Chào mừng bạn đến với thế giới cổ xưa!"
        """
        header = f"# {item.filename}:{item.linenumber}\ntranslate {self.language} {item.translation_id}:\n\n"
        comment = f"{self.INDENT}# {item.original_statement_code}\n"

        # Generate translated statement code
        translated_code = get_say_code(
            who=item.who,
            what=item.translated_text,
            attributes=item.attributes,
            temporary_attributes=item.temporary_attributes,
            with_=item.with_,
            interact=item.interact,
        )
        body = f"{self.INDENT}{translated_code}\n\n"
        return header + comment + body

    def format_strings_file(self, items: List[UIStringTranslationItem]) -> str:
        """
        Formats UI strings file:
          translate vietnamese strings:

              # game/screens.rpy:96
              old "Start"
              new "Bắt đầu"
        """
        lines = [f"translate {self.language} strings:\n\n"]
        for it in items:
            lines.append(f"{self.INDENT}# {it.filename}:{it.linenumber}\n")
            lines.append(f"{self.INDENT}old {encode_say_string(it.original_text)}\n")
            lines.append(f"{self.INDENT}new {encode_say_string(it.translated_text)}\n\n")
        return "".join(lines)

    def generate_font_overrides(self, fallback_font_path: str = "tl/vietnamese/fonts/fallback.ttf") -> str:
        """
        Generates FontGroup override script so all 134 Vietnamese NFC glyphs render cleanly.
        """
        return f"""# Generated by Renslate - FontGroup Fallback Override for Vietnamese NFC Glyphs
init python:
    # Set default dialogue and GUI font replacement
    try:
        import renpy
        # Style definition for font replacement
        renpy.config.font_replacement_map["default"] = "{fallback_font_path}"
    except Exception:
        pass
"""

    def export_package(
        self,
        output_dir: Path,
        dialogue_items: List[TranslationItem],
        string_items: List[UIStringTranslationItem],
        fallback_font_bytes: Optional[bytes] = None,
    ) -> Dict[str, Path]:
        """
        Writes all translation files into output_dir (e.g. game/tl/vietnamese/).
        """
        tl_root = output_dir / "tl" / self.language
        tl_root.mkdir(parents=True, exist_ok=True)
        created_files: Dict[str, Path] = {}

        # 1. Group dialogue by source filename
        files_map: Dict[str, List[TranslationItem]] = {}
        for item in dialogue_items:
            # Normalize filename (e.g. game/script.rpy -> script.rpy)
            base_name = Path(item.filename).name
            if not base_name.endswith(".rpy"):
                base_name += ".rpy"
            if base_name not in files_map:
                files_map[base_name] = []
            files_map[base_name].append(item)

        for base_name, items in files_map.items():
            content = []
            for it in items:
                content.append(self.format_dialogue_block(it))
            out_file = tl_root / base_name
            # Write ensuring strictly 0 tabs and 4 spaces
            full_text = "".join(content)
            assert "\t" not in full_text, f"Forbidden tab character detected in {base_name}"
            out_file.write_text(full_text, encoding="utf-8")
            created_files[base_name] = out_file

        # 2. UI strings file
        if string_items:
            strings_file = tl_root / "common.rpy"
            strings_text = self.format_strings_file(string_items)
            assert "\t" not in strings_text, "Forbidden tab character detected in common.rpy"
            strings_file.write_text(strings_text, encoding="utf-8")
            created_files["common.rpy"] = strings_file

        # 3. Font configuration
        fonts_script = tl_root / "00_renloc_fonts.rpy"
        fonts_text = self.generate_font_overrides()
        fonts_script.write_text(fonts_text, encoding="utf-8")
        created_files["00_renloc_fonts.rpy"] = fonts_script

        if fallback_font_bytes:
            fonts_dir = tl_root / "fonts"
            fonts_dir.mkdir(parents=True, exist_ok=True)
            font_path = fonts_dir / "fallback.ttf"
            font_path.write_bytes(fallback_font_bytes)
            created_files["fallback.ttf"] = font_path

        return created_files
