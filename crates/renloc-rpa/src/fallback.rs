//! fallback.rs
//! In-Game VFS Fallback mechanism for advanced obfuscated Ren'Py archives
//! such as ZiX-12A and ZiX-12B.
//!
//! Generates a safe, non-crashing Ren'Py script with `init -999 python:` that
//! invokes `renpy.loader.load()` to extract virtual assets within the live engine.

use std::fs;
use std::path::{Path, PathBuf};

use crate::header::RpaVersion;

/// Checks whether an archive version requires In-Game VFS Fallback.
pub fn is_fallback_required(version: &RpaVersion) -> bool {
    matches!(version, RpaVersion::ZiX12A | RpaVersion::ZiX12B)
}

#[derive(Debug, Clone)]
pub struct FallbackConfig {
    pub auto_dump: bool,
    pub dump_dir_name: String,
    pub target_extensions: Vec<String>,
}

impl Default for FallbackConfig {
    fn default() -> Self {
        Self {
            auto_dump: true,
            dump_dir_name: ".renslate_fallback_extracted".to_string(),
            target_extensions: vec![
                ".rpy".to_string(),
                ".rpyc".to_string(),
                ".rpym".to_string(),
                ".rpymc".to_string(),
                ".json".to_string(),
                ".txt".to_string(),
            ],
        }
    }
}

/// Generates an In-Game VFS Fallback `.rpy` script with `init -999 python:`.
pub fn generate_in_game_fallback_script(config: Option<&FallbackConfig>) -> String {
    let cfg = match config {
        Some(c) => c.clone(),
        None => FallbackConfig::default(),
    };

    let exts = cfg
        .target_extensions
        .iter()
        .map(|e| format!("\"{}\"", e))
        .collect::<Vec<_>>()
        .join(", ");

    let mut script = String::new();
    script.push_str("# ==============================================================================\n");
    script.push_str("# Ren'Py In-Game VFS Fallback Loader for Renslate (ZiX-12A / ZiX-12B Archives)\n");
    script.push_str("# Auto-generated by renloc-rpa\n");
    script.push_str("# ==============================================================================\n\n");
    script.push_str("init -999 python:\n");
    script.push_str("    import os\n");
    script.push_str("    import sys\n");
    script.push_str("    import json\n");
    script.push_str("    import renpy\n\n");
    script.push_str("    class RenslateVfsFallback(object):\n");
    script.push_str("        \"\"\"\n");
    script.push_str("        Safe In-Game VFS Fallback bridge for proprietary or encrypted archives\n");
    script.push_str("        (e.g., ZiX-12A, ZiX-12B) where static offline unpickling/extraction is not possible.\n");
    script.push_str("        Uses renpy.loader.load() within the live Ren'Py runtime environment.\n");
    script.push_str("        \"\"\"\n\n");
    script.push_str("        @classmethod\n");
    script.push_str("        def can_load(cls, filename):\n");
    script.push_str("            try:\n");
    script.push_str("                if hasattr(renpy.loader, \"loadable\"):\n");
    script.push_str("                    return renpy.loader.loadable(filename)\n");
    script.push_str("                return False\n");
    script.push_str("            except Exception:\n");
    script.push_str("                return False\n\n");
    script.push_str("        @classmethod\n");
    script.push_str("        def safe_load(cls, filename):\n");
    script.push_str("            \"\"\"\n");
    script.push_str("            Safely loads raw binary content using renpy.loader.load().\n");
    script.push_str("            Returns bytes on success, or None on failure.\n");
    script.push_str("            \"\"\"\n");
    script.push_str("            try:\n");
    script.push_str("                if not cls.can_load(filename):\n");
    script.push_str("                    return None\n");
    script.push_str("                with renpy.loader.load(filename) as f:\n");
    script.push_str("                    return f.read()\n");
    script.push_str("            except Exception as exc:\n");
    script.push_str("                try:\n");
    script.push_str("                    renpy.log(\"Renslate VFS Fallback load error: %s\" % (exc,))\n");
    script.push_str("                except Exception:\n");
    script.push_str("                    pass\n");
    script.push_str("                return None\n\n");
    script.push_str("        @classmethod\n");
    script.push_str("        def list_all_files(cls):\n");
    script.push_str("            files = set()\n");
    script.push_str("            try:\n");
    script.push_str("                if hasattr(renpy.loader, \"listdirfiles\"):\n");
    script.push_str("                    for dirpath, file_list in renpy.loader.listdirfiles():\n");
    script.push_str("                        for fn in file_list:\n");
    script.push_str("                            normalized = fn.replace(\"\\\\\", \"/\").lstrip(\"/\")\n");
    script.push_str("                            files.add(normalized)\n");
    script.push_str("            except Exception as exc:\n");
    script.push_str("                try:\n");
    script.push_str("                    renpy.log(\"Renslate VFS Fallback listdirfiles error: %s\" % (exc,))\n");
    script.push_str("                except Exception:\n");
    script.push_str("                    pass\n");
    script.push_str("            return sorted(list(files))\n\n");
    script.push_str("        @classmethod\n");
    script.push_str("        def dump_file(cls, filename, target_path):\n");
    script.push_str("            data = cls.safe_load(filename)\n");
    script.push_str("            if data is None:\n");
    script.push_str("                return False\n");
    script.push_str("            target_dir = os.path.dirname(target_path)\n");
    script.push_str("            if target_dir and not os.path.exists(target_dir):\n");
    script.push_str("                os.makedirs(target_dir, exist_ok=True)\n");
    script.push_str("            with open(target_path, \"wb\") as f:\n");
    script.push_str("                f.write(data)\n");
    script.push_str("            return True\n\n");
    script.push_str("        @classmethod\n");
    script.push_str(&format!("        def dump_matching_files(cls, target_dir, extensions=({},)):\n", exts));
    script.push_str("            all_files = cls.list_all_files()\n");
    script.push_str("            dumped = []\n");
    script.push_str("            for fn in all_files:\n");
    script.push_str("                if any(fn.lower().endswith(ext) for ext in extensions):\n");
    script.push_str("                    out_path = os.path.join(target_dir, fn)\n");
    script.push_str("                    if cls.dump_file(fn, out_path):\n");
    script.push_str("                        dumped.append(fn)\n");
    script.push_str("            return dumped\n\n");
    script.push_str("        @classmethod\n");
    script.push_str("        def export_manifest(cls, manifest_path):\n");
    script.push_str("            all_files = cls.list_all_files()\n");
    script.push_str("            manifest = {\n");
    script.push_str("                \"version\": \"1.0\",\n");
    script.push_str("                \"total_files\": len(all_files),\n");
    script.push_str("                \"files\": all_files,\n");
    script.push_str("            }\n");
    script.push_str("            manifest_dir = os.path.dirname(manifest_path)\n");
    script.push_str("            if manifest_dir and not os.path.exists(manifest_dir):\n");
    script.push_str("                os.makedirs(manifest_dir, exist_ok=True)\n");
    script.push_str("            with open(manifest_path, \"w\", encoding=\"utf-8\") as f:\n");
    script.push_str("                json.dump(manifest, f, indent=2)\n");
    script.push_str("            return manifest\n\n");
    script.push_str("    try:\n");
    script.push_str("        _game_dir = getattr(renpy.config, \"gamedir\", None) or os.getcwd()\n");
    script.push_str("        _trigger_file = os.path.join(_game_dir, \".renslate_dump_trigger\")\n");
    script.push_str("        _env_dump = os.environ.get(\"RENSLATE_FALLBACK_DUMP\")\n");
    script.push_str(&format!("        _out_dir = os.environ.get(\"RENSLATE_FALLBACK_OUTPUT_DIR\") or os.path.join(_game_dir, \"{}\")\n", cfg.dump_dir_name));
    if cfg.auto_dump {
        script.push_str("        if _env_dump or os.path.exists(_trigger_file) or not os.path.exists(_out_dir):\n");
    } else {
        script.push_str("        if _env_dump or os.path.exists(_trigger_file):\n");
    }
    script.push_str("            RenslateVfsFallback.dump_matching_files(_out_dir)\n");
    script.push_str("            RenslateVfsFallback.export_manifest(os.path.join(_out_dir, \"renslate_manifest.json\"))\n");
    script.push_str("            if os.path.exists(_trigger_file):\n");
    script.push_str("                try:\n");
    script.push_str("                    os.remove(_trigger_file)\n");
    script.push_str("                except Exception:\n");
    script.push_str("                    pass\n");
    script.push_str("    except Exception:\n");
    script.push_str("        pass\n");

    script
}

/// Writes the In-Game VFS Fallback `.rpy` script to disk in `target_dir`.
pub fn write_in_game_fallback_script<P: AsRef<Path>>(
    target_dir: P,
    config: Option<&FallbackConfig>,
) -> Result<PathBuf, std::io::Error> {
    let dir = target_dir.as_ref();
    fs::create_dir_all(dir)?;
    let file_path = dir.join("00_renloc_vfs_fallback.rpy");
    let script = generate_in_game_fallback_script(config);
    fs::write(&file_path, script)?;
    Ok(file_path)
}
